export function matchStateName(rawState?: string): string {
  if (!rawState) return '';
  const clean = rawState.trim().toLowerCase();
  if (STATE_ALIASES[clean]) return STATE_ALIASES[clean];
  const directMatch = INDIAN_STATES.find(s => s.toLowerCase() === clean);
  if (directMatch) return directMatch;
  const partial = INDIAN_STATES.find(s => s.toLowerCase().includes(clean) || clean.includes(s.toLowerCase()));
  return partial || rawState.trim();
}

export function matchDistrictName(stateName: string, rawDistrict?: string): string {
  if (!rawDistrict) return '';
  const clean = rawDistrict.trim().toLowerCase();
  const districts = getDistrictsForState(stateName);
  
  if (DISTRICT_ALIASES[clean]) {
    const alias = DISTRICT_ALIASES[clean];
    if (districts.includes(alias)) return alias;
  }

  const direct = districts.find(d => d.toLowerCase() === clean);
  if (direct) return direct;

  const partial = districts.find(d => d.toLowerCase().includes(clean) || clean.includes(d.toLowerCase()));
  return partial || rawDistrict.trim();
}

export interface PincodeLookupResult {
  state: string;
  district: string;
  city: string;
  postOffices: string[];
}

/**
 * Free public India Postal PIN code lookup with fast fallback & local normalization.
 */
export async function lookupPincode(pincode: string): Promise<PincodeLookupResult | null> {
  const cleanPin = pincode.replace(/\D/g, '').trim();
  if (cleanPin.length !== 6) return null;

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4000); // 4s timeout

    const res = await fetch(`https://api.postalpincode.in/pincode/${cleanPin}`, {
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    if (!res.ok) return null;

    const data = await res.json();
    if (!Array.isArray(data) || !data[0] || data[0].Status !== 'Success' || !Array.isArray(data[0].PostOffice)) {
      return null;
    }

    const postOffices = data[0].PostOffice;
    if (postOffices.length === 0) return null;

    const rawState = postOffices[0].State || '';
    const rawDistrict = postOffices[0].District || '';

    const matchedState = matchStateName(rawState);
    const matchedDistrict = matchDistrictName(matchedState, rawDistrict);

    const poNames = Array.from(new Set(postOffices.map((p: any) => p.Name).filter(Boolean))) as string[];
    const primaryCity = poNames[0] || matchedDistrict || rawDistrict;

    return {
      state: matchedState || rawState,
      district: matchedDistrict || rawDistrict,
      city: primaryCity,
      postOffices: poNames
    };
  } catch (err) {
    // Timeout or network offline — fallback gracefully
    return null;
  }
}
