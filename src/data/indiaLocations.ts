export const INDIAN_STATES: string[] = Object.keys(INDIAN_STATES_AND_DISTRICTS).sort();

export function getDistrictsForState(stateName?: string): string[] {
  if (!stateName) return [];
  const cleanName = stateName.trim().toLowerCase();
  const matchedKey = Object.keys(INDIAN_STATES_AND_DISTRICTS).find(
    s => s.toLowerCase() === cleanName
  );
  return matchedKey ? INDIAN_STATES_AND_DISTRICTS[matchedKey] : [];
}

